-- ============================================================
-- INVENTORY VERIFICATION
-- ============================================================

SELECT
    w."name" AS warehouse,
    s."sku",
    i."available",
    i."reserved",
    i."status"
FROM "Inventory" i
JOIN "Warehouse" w
    ON w."id" = i."warehouseId"
JOIN "SKU" s
    ON s."id" = i."skuId"
ORDER BY w."name", s."sku";